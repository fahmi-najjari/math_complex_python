import cmath

z = 2 + 3j

print("z =", z)


# ------------------------------------------------------------
# cmath.exp(z)
# ------------------------------------------------------------
#
# Exponentielle complexe : e^z

print("\ncmath.exp(z) :")
print(cmath.exp(z))


# ------------------------------------------------------------
# cmath.log(z)
# ------------------------------------------------------------
#
# Logarithme naturel complexe

print("\ncmath.log(z) :")
print(cmath.log(z))


# ------------------------------------------------------------
# cmath.log10(z)
# ------------------------------------------------------------
#
# Logarithme en base 10

print("\ncmath.log10(z) :")
print(cmath.log10(z))


# ------------------------------------------------------------
# Logarithme avec une autre base
# ------------------------------------------------------------
#
# cmath.log(z, base)

print("\nLogarithme base 2 :")
print(cmath.log(z, 2))


