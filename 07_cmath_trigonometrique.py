import cmath

z = 2 + 3j

print("z =", z)


# Sinus
print("\nsin(z) =", cmath.sin(z))


# Cosinus
print("cos(z) =", cmath.cos(z))


# Tangente
print("tan(z) =", cmath.tan(z))


# Fonctions reciproques

print("\nasin(z) =", cmath.asin(z))
print("acos(z) =", cmath.acos(z))
print("atan(z) =", cmath.atan(z))


