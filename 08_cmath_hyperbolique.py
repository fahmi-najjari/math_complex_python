import cmath

z = 2 + 3j

print("z =", z)


print("\nsinh(z) =", cmath.sinh(z))
print("cosh(z) =", cmath.cosh(z))
print("tanh(z) =", cmath.tanh(z))


print("\nasinh(z) =", cmath.asinh(z))
print("acosh(z) =", cmath.acosh(z))
print("atanh(z) =", cmath.atanh(z))


