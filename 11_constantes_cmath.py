import cmath


print("cmath.pi =", cmath.pi)

print("cmath.e =", cmath.e)

print("cmath.tau =", cmath.tau)


# Infini reel
print("cmath.inf =", cmath.inf)


# Infini imaginaire
print("cmath.infj =", cmath.infj)


# Not a Number
print("cmath.nan =", cmath.nan)


# NaN imaginaire
print("cmath.nanj =", cmath.nanj)
