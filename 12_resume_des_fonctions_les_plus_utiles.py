import cmath
import math

z = 3 + 4j


# ------------------------------------------------------------
# CREATION
# ------------------------------------------------------------

print("Creation :")
print(3 + 4j)
print(complex(3, 4))


# ------------------------------------------------------------
# PARTIES DU COMPLEXE
# ------------------------------------------------------------

print("\nPartie reelle :", z.real)
print("Partie imaginaire :", z.imag)


# ------------------------------------------------------------
# MODULE
# ------------------------------------------------------------

print("\nModule :", abs(z))


# ------------------------------------------------------------
# CONJUGUE
# ------------------------------------------------------------

print("Conjugue :", z.conjugate())


# ------------------------------------------------------------
# RACINE CARREE
# ------------------------------------------------------------

print("Racine :", cmath.sqrt(z))


# ------------------------------------------------------------
# EXPONENTIELLE
# ------------------------------------------------------------

print("Exponentielle :", cmath.exp(z))


# ------------------------------------------------------------
# LOGARITHME
# ------------------------------------------------------------

print("Logarithme :", cmath.log(z))


# ------------------------------------------------------------
# TRIGONOMETRIE
# ------------------------------------------------------------

print("Sinus :", cmath.sin(z))
print("Cosinus :", cmath.cos(z))
print("Tangente :", cmath.tan(z))


# ------------------------------------------------------------
# ARGUMENT
# ------------------------------------------------------------

theta = cmath.phase(z)

print("Argument radians :", theta)
print("Argument degres :", math.degrees(theta))


# ------------------------------------------------------------
# FORME POLAIRE
# ------------------------------------------------------------

r, theta = cmath.polar(z)

print("Module polaire :", r)
print("Angle polaire :", theta)


# ------------------------------------------------------------
# RETOUR POLAIRE -> COMPLEXE
# ------------------------------------------------------------

print("rect :", cmath.rect(r, theta))


# ------------------------------------------------------------
# COMPARAISON APPROXIMATIVE
# ------------------------------------------------------------

print(
    "isclose :",
    cmath.isclose(z, 3 + 4.00000000001j)
)


