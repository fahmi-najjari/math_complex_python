print("Bonjour")

print(5)

print(3 + 4)


# ------------------------------------------------------------
# VARIABLES
# ------------------------------------------------------------
#
# Une variable permet de stocker une valeur.
#
# Syntaxe :
#
# nom = valeur
#
# Le symbole = signifie ici "affecter une valeur".
# Ce n'est pas une equation mathematique.
# ------------------------------------------------------------

x = 10
y = 3

print(x)
print(y)

print(x + y)


# On peut changer la valeur d'une variable.

x = 20

print(x)


# ------------------------------------------------------------
# TYPE D'UNE VARIABLE
# ------------------------------------------------------------
#
# type() permet de connaitre le type d'une valeur.
# ------------------------------------------------------------

a = 5
b = 2.5

print(type(a))
print(type(b))


# int   -> entier
# float -> nombre decimal
# str   -> texte
# complex -> nombre complexe


