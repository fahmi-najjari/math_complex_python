a = 10
b = 3


# Addition
print("Addition :", a + b)


# Soustraction
print("Soustraction :", a - b)


# Multiplication
print("Multiplication :", a * b)


# Division
print("Division :", a / b)


# ------------------------------------------------------------
# PUISSANCE
# ------------------------------------------------------------
#
# En mathematiques :
# 2^3
#
# En Python :
# 2 ** 3
#
# ATTENTION :
# Le symbole ^ n'est PAS utilise pour la puissance en Python.
# ------------------------------------------------------------

print("2 puissance 3 =", 2 ** 3)


# ------------------------------------------------------------
# RESTE DE LA DIVISION : %
# ------------------------------------------------------------
#
# Exemple :
#
# 20 = 6 * 3 + 2
#
# Donc :
# 20 % 3 = 2
# ------------------------------------------------------------

print("20 % 3 =", 20 % 3)


# Division entiere
print("20 // 3 =", 20 // 3)


# ------------------------------------------------------------
