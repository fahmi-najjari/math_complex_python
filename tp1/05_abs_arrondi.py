import math


# ------------------------------------------------------------
# abs()
# ------------------------------------------------------------
#
# abs() retourne la valeur absolue.
#
# abs() est deja integree dans Python.
# On n'ecrit pas math.abs().
# ------------------------------------------------------------

print("abs(-10) =", abs(-10))

print("abs(10) =", abs(10))


# Python calcule d'abord l'expression.

print("abs(-10 + 3) =", abs(-10 + 3))

# Python fait :
# -10 + 3 = -7
# puis :
# abs(-7) = 7


# ------------------------------------------------------------
# round()
# ------------------------------------------------------------
#
# round() arrondit un nombre.
# ------------------------------------------------------------

print("round(3.6) =", round(3.6))

print("round(3.2) =", round(3.2))


# Nombre de chiffres apres la virgule :

print("round(3.141592, 2) =", round(3.141592, 2))


# ------------------------------------------------------------
# math.floor()
# ------------------------------------------------------------
#
# floor -> arrondi vers le bas
# ------------------------------------------------------------

print("floor(3.9) =", math.floor(3.9))


# ------------------------------------------------------------
# math.ceil()
# ------------------------------------------------------------
#
# ceil -> arrondi vers le haut
# ------------------------------------------------------------

print("ceil(3.1) =", math.ceil(3.1))


