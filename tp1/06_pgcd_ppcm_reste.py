import math


# ------------------------------------------------------------
# RESTE : %
# ------------------------------------------------------------

print("20 % 3 =", 20 % 3)

print("20 % 33 =", 20 % 33)

# Pourquoi 20 % 33 = 20 ?
#
# Parce que 33 ne peut pas entrer une fois dans 20.
# Le quotient entier est 0 et le reste est 20.


# ------------------------------------------------------------
# PGCD : math.gcd()
# ------------------------------------------------------------
#
# gcd = Greatest Common Divisor
#
# En francais :
# PGCD
# ------------------------------------------------------------

print("PGCD de 325 et 243 =", math.gcd(325, 243))


# ------------------------------------------------------------
# PPCM : math.lcm()
# ------------------------------------------------------------
#
# lcm = Least Common Multiple
#
# En francais :
# PPCM
# ------------------------------------------------------------

print("PPCM de 325 et 243 =", math.lcm(325, 243))


