import math


# ------------------------------------------------------------
# RACINE CARREE
# ------------------------------------------------------------

print("sqrt(25) =", math.sqrt(25))


# Exemple avec une variable

x = 81

print("sqrt(x) =", math.sqrt(x))


# ------------------------------------------------------------
# LOGARITHME NATUREL
# ------------------------------------------------------------
#
# math.log(x) = ln(x)
# ------------------------------------------------------------

print("ln(10) =", math.log(10))


# ------------------------------------------------------------
# LOGARITHME BASE 10
# ------------------------------------------------------------

print("log10(100) =", math.log10(100))


# ------------------------------------------------------------
# LOGARITHME DANS UNE AUTRE BASE
# ------------------------------------------------------------

print("log base 2 de 8 =", math.log(8, 2))


# ------------------------------------------------------------
# EXPONENTIELLE
# ------------------------------------------------------------
#
# math.exp(x) = e^x
# ------------------------------------------------------------

print("e^1 =", math.exp(1))

print("e^2 =", math.exp(2))


