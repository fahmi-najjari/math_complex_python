# ============================================================
# 09 - PARTIE REELLE, PARTIE IMAGINAIRE, MODULE, CONJUGUE
# ============================================================

z = 3 + 4j

print("z =", z)


# ------------------------------------------------------------
# PARTIE REELLE : .real
# ------------------------------------------------------------

print("Partie reelle =", z.real)


# ------------------------------------------------------------
# PARTIE IMAGINAIRE : .imag
# ------------------------------------------------------------

print("Partie imaginaire =", z.imag)


# ------------------------------------------------------------
# MODULE : abs()
# ------------------------------------------------------------
#
# abs() fonctionne aussi avec les nombres complexes.
# ------------------------------------------------------------

print("Module =", abs(z))


# ------------------------------------------------------------
# CONJUGUE : .conjugate()
# ------------------------------------------------------------

print("Conjugue =", z.conjugate())


# ------------------------------------------------------------
# DIFFERENCE ENTRE ATTRIBUT ET METHODE
# ------------------------------------------------------------
#
# z.real
# z.imag
#
# pas de parentheses
#
#
# z.conjugate()
#
# parentheses obligatoires
#
# ------------------------------------------------------------


# Exemple :

z2 = -5 + 12j

print("\nz2 =", z2)

print("Re(z2) =", z2.real)

print("Im(z2) =", z2.imag)

print("|z2| =", abs(z2))

print("Conjugue(z2) =", z2.conjugate())


