import math
import cmath


# ------------------------------------------------------------
# PYTHON DE BASE
# ------------------------------------------------------------

x = 10

print(x)

print(type(x))


# ------------------------------------------------------------
# OPERATIONS
# ------------------------------------------------------------

print(2 + 3)

print(2 - 3)

print(2 * 3)

print(2 / 3)

print(2 ** 3)

print(20 % 3)


# ------------------------------------------------------------
# MATH
# ------------------------------------------------------------

print(math.pi)

print(math.sqrt(25))

print(math.gcd(24, 18))

print(math.lcm(12, 18))

print(math.log(10))

print(math.log10(100))

print(math.exp(1))

print(math.sin(math.pi / 2))

print(math.cos(0))

print(math.tan(math.pi / 4))


# ------------------------------------------------------------
# FONCTIONS PYTHON UTILES
# ------------------------------------------------------------

print(abs(-10))

print(round(3.14159, 2))

print(math.floor(3.9))

print(math.ceil(3.1))


# ------------------------------------------------------------
# COMPLEXES
# ------------------------------------------------------------

z = 3 + 4j

print(z)

print(type(z))

print(z.real)

print(z.imag)

print(abs(z))

print(z.conjugate())


# ------------------------------------------------------------
# CMATH
# ------------------------------------------------------------

print(cmath.sqrt(-4))

print(cmath.sqrt(z))

print(cmath.exp(z))

print(cmath.log(z))

print(cmath.sin(z))

print(cmath.cos(z))


# ------------------------------------------------------------
# ARGUMENT / POLAIRE
# ------------------------------------------------------------

print(cmath.phase(z))

print(cmath.polar(z))

print(cmath.rect(5, math.pi / 4))


